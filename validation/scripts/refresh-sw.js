'use strict';
// Builds public/manager/sw.js and public/employee/sw.js: an app-shell cache for those two pages only.
// SHELL = the page itself + every same-origin file its HTML loads + manifest and icons.
// VERSION = SHA-256 of all shell file contents: any changed file gives a new sw.js, so the browser installs a
// fresh cache and deletes the old one. Data (Firebase, other origins, POST) is never cached.
// Usage: node scripts/refresh-sw.js          (write)
//        node scripts/refresh-sw.js --check  (exit 1 if a sw.js is stale; used by scripts/check.js)
const fs = require('node:fs'), path = require('node:path'), { createHash } = require('node:crypto');
const root = path.resolve(__dirname, '..');
const local = url => url.startsWith('/manager/assets/') ? path.join(root, 'public/assets', url.slice('/manager/assets/'.length)) : path.join(root, 'public', url);

function build(page) {
  const scope = `/${page}/`, html = fs.readFileSync(path.join(root, 'public', page, 'index.html'), 'utf8');
  const refs = [...html.matchAll(/(?:src|href)="(\/[^"?#]+)"/g)].map(m => m[1]).filter(u => u.startsWith('/manager/') || u.startsWith(scope));
  const extras = fs.readdirSync(path.join(root, 'public', page)).filter(f => /^(manifest\.json|icon-.*\.png)$/.test(f)).map(f => scope + f);
  const shell = [...new Set([scope, ...refs, ...extras])].sort();
  const hash = createHash('sha256');
  for (const url of shell) { const file = url === scope ? path.join(root, 'public', page, 'index.html') : local(url); hash.update(url + '\n'); hash.update(fs.readFileSync(file)); }
  const version = hash.digest('hex').slice(0, 16);
  return `'use strict';
// GENERATED by scripts/refresh-sw.js - do not edit by hand.
// App-shell cache for ${scope} only (never the site root, never another app on this site).
// Cache-first for the files listed in SHELL; everything else (Firebase, data, other origins, POST) goes to the
// network untouched. A new release changes VERSION, so the browser installs a fresh cache and deletes the old one.
const VERSION = '${version}';
const SCOPE = '${scope}';
const SHELL = ${JSON.stringify(shell, null, 2)};
const CACHE = 'basma-shell-${page}-' + VERSION;
self.addEventListener('install', event => event.waitUntil((async () => {
  const cache = await caches.open(CACHE);
  await cache.addAll(SHELL.map(url => new Request(url, { cache: 'reload' })));
  await self.skipWaiting();
})()));
self.addEventListener('activate', event => event.waitUntil((async () => {
  for (const name of await caches.keys()) if (/^basma-/.test(name) && name !== CACHE) await caches.delete(name);
  await self.clients.claim();
})()));
self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  const key = url.pathname === SCOPE + 'index.html' ? SCOPE : url.pathname;
  if (!SHELL.includes(key)) return;
  event.respondWith((async () => (await caches.match(key, { cacheName: CACHE })) || fetch(request))());
});
`;
}

function main() {
  const check = process.argv.includes('--check'), stale = [];
  for (const page of ['manager', 'employee']) {
    const file = path.join(root, 'public', page, 'sw.js'), next = build(page);
    if (check) { if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== next) stale.push(`public/${page}/sw.js`); }
    else fs.writeFileSync(file, next);
  }
  if (check && stale.length) { console.error(`Stale service worker (run node scripts/refresh-sw.js): ${stale.join(', ')}`); process.exit(1); }
  if (!check) console.log('service workers refreshed');
}
if (require.main === module) main();
module.exports = { build };
